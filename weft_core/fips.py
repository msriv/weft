FIPS_TO_ISO: dict[str, str] = dict(
    pair.split() for pair in _PAIRS.replace("\n", "").split("|") if pair.strip()
)


def iso_from_fips(code: str) -> str | None:
    """ISO 3166-1 alpha-2 for a GDELT FIPS code, or None if unmapped (never guess)."""
    return FIPS_TO_ISO.get(code.upper())
